export function weaponStats(id, level = 0) {
  const base = WEAPONS[id];
  if (!base) return null;
  if (base.kind === 'melee') {
    return {
      ...base,
      dmg: Math.round(base.dmg * (1 + level * 0.16)),
      range: base.range + level * 5,
      rate: base.rate * (1 + level * 0.04),
      level,
    };
  }
  const mag = Math.round(base.mag * (1 + level * 0.16));
  return {
    ...base,
    dmg: Math.round(base.dmg * (1 + level * 0.15) * 10) / 10,
    rate: base.rate * (1 + level * 0.03),
    mag,
    reload: base.reload * (1 - level * 0.05),
    spread: base.spread * (1 - level * 0.08),
    level,
  };
}

export function upgradeCost(level) {
  return {
    parts: 10 + level * 10,
    scrap: 25 + level * 22,
  };
}

